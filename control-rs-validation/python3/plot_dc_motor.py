#!/usr/bin/env python3
"""
plot_dc_motor.py

Diagnostic visualizer for the DC motor armature classical control example:
- Peripheral delay (tau_act = 500 us)
- Noisy actuator (voltage noise + saturation)
- Delayed & noisy 16-bit absolute position encoder (tau_sens = 500 us, 65,536 counts/turn)
- Dual Rust controller comparison: Controller A (Lead via DirectForm2T) vs Controller B (PID) vs Ideal Baseline

Loads `results/dc-motor.*.h5` generated by `cargo run` and renders a 4-panel dark-themed dashboard:
  1. Frequency Response (Bode magnitude, plant phase, loop delay penalty, and compensated loop)
  2. Root Locus Trajectory (Z-plane pole migration over loop gain sweep)
  3. Closed-Loop Position Tracking (Ideal vs Lead vs PID with 16-bit quantization & noise)
  4. Actuator Effort & Armature Current (Terminal voltage saturation and current response)

Usage:
  python3 plot_dc_motor.py [--show] [--json <path>] [--output <path>]
"""

